import math
tup1=(4 , 3 , 2 , 2 , -1 , 18)
tup2=(2 , 4 , 8 , 8 , 3 , 2 , 9)

prod_tup1=math.prod(tup1)
prod_tup2=math.prod(tup2)
total_prod=prod_tup1*prod_tup2

print("The Product of the first tuple is:", prod_tup1)
print("The Product of the second tuple is:" , prod_tup2)
print("The Total product of the given tuples are:", total_prod)